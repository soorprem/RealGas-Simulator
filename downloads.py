"""Downloads in native Streamlit and browser Python.
Stlite's media fetch transport can fail on static origins; direct data links avoid
that transport and download the exact same generated bytes locally.
"""
import base64
import html
import sys


def download_button(container,label,data,file_name,mime,**kwargs):
    if sys.platform == 'emscripten':
        payload=data.encode('utf-8') if isinstance(data,str) else bytes(data)
        encoded=base64.b64encode(payload).decode('ascii')
        container.markdown(
            f'<a download="{html.escape(file_name,quote=True)}" href="data:{mime};base64,{encoded}" '
            'style="display:inline-block;padding:0.55rem 0.9rem;margin:0.2rem 0;'
            'border:1px solid #bccdd8;border-radius:0.45rem;color:#173047;'
            'background:#fff;text-decoration:none;font-weight:500;">'
            f'{html.escape(label)}</a>',unsafe_allow_html=True)
        return None
    return container.download_button(label,data,file_name,mime,**kwargs)
